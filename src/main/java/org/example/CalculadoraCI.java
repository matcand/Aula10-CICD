package org.example;

/**
 * Classe da calculadora para demonstracao de Integracao Continua.
 */
public class CalculadoraCI {

    /**
     * Soma dois numeros inteiros.
     *
     * @param a primeiro numero.
     * @param b segundo numero.
     * @return resultado da soma.
     */
    public int somar(final int a, final int b) {
        return a + b;
    }

    /**
     * Subtrai dois numeros inteiros.
     *
     * @param a primeiro numero.
     * @param b segundo numero.
     * @return resultado da subtracao.
     */
    public int subtrair(final int a, final int b) {
        return a - b;
    }
}
